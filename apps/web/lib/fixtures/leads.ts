// `NOW` é congelado pra que as datas relativas sejam estáveis entre renders
// (sem isso, "última interação" mudava a cada SSR/CSR e quebrava a hidratação).
const NOW = new Date('2026-05-09T14:00:00-03:00');

/**
 * Deriva temperatura da última interação:
 *  - <3 dias → quente
 *  - 3–10 dias → morno
 *  - >10 dias → frio
 *  - sem interação → frio
 *
 * Em M11 essa heurística vira sinal de IA (sentimento + sinais de compra).
 */
export function temperatureFromLastInteraction(iso?: string): LeadTemperature {
  if (!iso) return 'cold';
  const days = differenceInDays(NOW, parseISO(iso));
  if (days < 3) return 'hot';
  if (days <= 10) return 'warm';
  return 'cold';
}

